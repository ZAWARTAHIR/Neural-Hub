import { useCallback, useEffect, useMemo, useState } from "react";
import { Link } from "react-router-dom";
import { isSupabaseConfigured } from "../../lib/supabase.js";
import { loadWhatsappMessages } from "../../lib/media.js";
import { Icon } from "../../components/icons/Icons.jsx";
import "../../styles/blog-admin.css";
import "../../styles/image-admin.css";

const formatDate = (value) => {
  const d = new Date(value);
  return value && !Number.isNaN(d.getTime())
    ? d.toLocaleString(undefined, { year: "numeric", month: "short", day: "numeric", hour: "numeric", minute: "2-digit" })
    : "—";
};

// WhatsApp broadcast messages generated by campaigns (public.campaigns results).
export default function WhatsappPage() {
  const [messages, setMessages] = useState([]);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState("");
  const [query, setQuery] = useState("");
  const [copiedId, setCopiedId] = useState(null);

  const load = useCallback(async () => {
    if (!isSupabaseConfigured) {
      setError("Supabase is not configured.");
      setLoading(false);
      return;
    }
    setLoading(true);
    setError("");
    try {
      setMessages(await loadWhatsappMessages());
    } catch (err) {
      setError(err.message || "Could not load WhatsApp messages.");
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => {
    load();
  }, [load]);

  const visible = useMemo(() => {
    const q = query.trim().toLowerCase();
    if (!q) return messages;
    return messages.filter((m) => [m.topic, m.message].some((v) => String(v || "").toLowerCase().includes(q)));
  }, [messages, query]);

  async function copy(m) {
    try {
      await navigator.clipboard.writeText(m.message);
      setCopiedId(m.id);
      setTimeout(() => setCopiedId((id) => (id === m.id ? null : id)), 1500);
    } catch {
      // Clipboard may be blocked.
    }
  }

  return (
    <div className="ba">
      <header className="ba-head">
        <div>
          <h1>WhatsApp</h1>
          <p>Broadcast messages written by your campaigns, ready to copy and send.</p>
        </div>
        <button type="button" className="ba-btn" onClick={load} disabled={loading}>
          <Icon name="refresh" size={15} className={loading ? "ba-spin" : ""} />
          {loading ? "Refreshing…" : "Refresh"}
        </button>
      </header>

      <div className="ba-toolbar">
        <label className="ba-search">
          <Icon name="search" size={16} />
          <input
            type="search"
            value={query}
            onChange={(e) => setQuery(e.target.value)}
            placeholder="Search messages or campaign prompts"
            aria-label="Search WhatsApp messages"
          />
        </label>
      </div>

      {error && (
        <div className="ba-error" role="alert">
          <strong>Couldn&rsquo;t load messages.</strong> {error}
        </div>
      )}

      <section className="wa-grid" aria-busy={loading}>
        {loading && messages.length === 0
          ? Array.from({ length: 3 }, (_, i) => <div key={i} className="wa-card ia-skeleton" />)
          : visible.map((m) => (
              <article key={m.id} className="wa-card">
                <header>
                  <span className="wa-topic" title={m.topic}>{m.topic}</span>
                  <small>{formatDate(m.createdAt)}</small>
                </header>
                <p className="wa-message">{m.message}</p>
                <div className="wa-actions">
                  <button type="button" className="ba-btn" onClick={() => copy(m)}>
                    <Icon name={copiedId === m.id ? "check" : "copy"} size={15} />
                    {copiedId === m.id ? "Copied" : "Copy message"}
                  </button>
                  <a
                    className="ba-btn"
                    href={`https://wa.me/?text=${encodeURIComponent(m.message)}`}
                    target="_blank"
                    rel="noreferrer"
                  >
                    <Icon name="whatsapp" size={15} />
                    Open in WhatsApp
                  </a>
                </div>
              </article>
            ))}
      </section>

      {!loading && !error && visible.length === 0 && (
        <div className="ba-list">
          <div className="ba-empty">
            <Icon name="whatsapp" size={22} />
            <strong>{messages.length === 0 ? "No WhatsApp messages yet" : "No messages match your search"}</strong>
            <span>
              {messages.length === 0 ? (
                <>
                  Generate a WhatsApp campaign from <Link to="/dashboard/campaign">New campaign</Link> and it will show up here.
                </>
              ) : (
                "Try a different search."
              )}
            </span>
          </div>
        </div>
      )}
    </div>
  );
}
